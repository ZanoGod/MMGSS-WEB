  function normalize(s) {
    return s.replace(/\s+/g, " ").trim();
  }
  function collect() {
    const walker = document.createTreeWalker(
      document.body,
      NodeFilter.SHOW_TEXT,
    );
    while (walker.nextNode()) {
      const n = walker.currentNode;
      if (
        n.parentElement &&
        ["SCRIPT", "STYLE", "NOSCRIPT"].includes(n.parentElement.tagName)
      )
        continue;
      if (!originals.has(n)) originals.set(n, n.nodeValue);
    }
    document.querySelectorAll("[aria-label],[title],[alt]").forEach((el) => {
      if (!attrOriginals.has(el))
        attrOriginals.set(el, {
          "aria-label": el.getAttribute("aria-label"),
          title: el.getAttribute("title"),
          alt: el.getAttribute("alt"),
        });
    });
  }
  function translateNode(node, dict) {
    const original = originals.get(node);
    if (original == null) return;
    const key = normalize(original);
    if (dict[key]) {
      const leading = original.match(/^\s*/)?.[0] || "";
      const trailing = original.match(/\s*$/)?.[0] || "";
      node.nodeValue = leading + dict[key] + trailing;
    } else node.nodeValue = original;
  }
  function translateAttributes(dict) {
    attrOriginals.forEach?.(() => {});
    document.querySelectorAll("[aria-label],[title],[alt]").forEach((el) => {
      const o = attrOriginals.get(el);
      if (!o) return;
      ["aria-label", "title", "alt"].forEach((a) => {
        if (o[a] == null) return;
        const key = normalize(o[a]);
        el.setAttribute(a, dict[key] || o[a]);
      });
    });
  }
  function translateDynamicValues(dict) {
    document.querySelectorAll("[data-job]").forEach((btn) => {
      [
        "role",
        "type",
        "location",
        "salary",
        "language",
        "duration",
        "summary",
        "requirements",
        "support",
      ].forEach((k) => {
        const attr = "data-" + k;
        const value = btn.getAttribute(attr);
        if (value && !btn.dataset["en" + k]) btn.dataset["en" + k] = value;
        const original = btn.dataset["en" + k];
        if (original)
          btn.setAttribute(attr, dict[normalize(original)] || original);
      });
    });
  }
